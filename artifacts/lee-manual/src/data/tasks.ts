function buildDependents(tasks: Omit<Task, "dependents">[]): Task[] {
  const dependentsMap: Record<number, number[]> = {};
  for (const t of tasks) {
    if (!dependentsMap[t.id]) dependentsMap[t.id] = [];
  }
  for (const t of tasks) {
    for (const dep of t.dependsOn) {
      if (!dependentsMap[dep]) dependentsMap[dep] = [];
      dependentsMap[dep].push(t.id);
    }
  }
  return tasks.map(t => ({ ...t, dependents: dependentsMap[t.id] || [] }));
}

